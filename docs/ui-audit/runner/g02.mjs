import { flow } from "./lib2.mjs";
await flow({ id: process.argv[2] || "G02-returning-patient-second-visit", role: "doctor", vp: "laptop" }, async (c) => {
  const p = c.page; const d = () => p.locator("dialog[open]");
  await c.go("/app/patients", "Doctor opens the Patients list");
  await c.click(p.getByRole("link", { name: "Neha Testcase" }).first(), "Open Neha Testcase (old finalised visit, ₹2,500 still due)");
  await c.look("Profile of a returning patient: what does the doctor see first?");
  await c.click(p.getByRole("button", { name: "New visit" }).or(p.getByRole("link", { name: "New visit" })), "Click New visit (no appointment today)");
  await c.look("New visit opens; side card 'Last visits' shows the previous visit");
  await c.type(p.getByLabel("Complaint"), "Pain in lower right tooth again", "Type chief complaint");
  await p.waitForTimeout(1800);
  await c.click(p.getByRole("tab", { name: "History", exact: true }), "Open the visit's History tab to see the old visit");
  await c.look("History tab inside the visit");
  await c.click(p.getByRole("tab", { name: "Visit", exact: true }), "Back to the Visit tab");
  await c.click(p.getByRole("group", { name: "Procedures done" }).getByRole("button").first(), "Pick the first procedure chip (Scaling) on the Visit screen");
  await c.look("Procedure added to the visit");
  await c.click(p.getByRole("button", { name: "Finalise visit" }), "Click Finalise visit (no prescription this time)");
  await c.click(d().getByRole("button", { name: "Finalise" }), "Confirm Finalise");
  await c.click(p.getByRole("button", { name: "Create bill" }), "Click Create bill");
  c.note("D5: Create bill issues the bill at once; there is no Issue step.");
  await c.look("Issued bill");
  await c.as("receptionist", "Switch to the receptionist");
  await c.go("/app/billing", "Receptionist opens Billing (dues list)");
  await c.look("Dues list: is Neha's new bill included? How much does she owe?");
  await c.click(p.getByRole("link", { name: /Neha Testcase/ }).first(), "Click Neha in the dues list");
  await c.click(p.getByRole("tab", { name: "Billing", exact: true }), "Open Billing tab");
  await c.look("Billing tab: two bills, balance");
  await c.type(p.getByLabel(/Amount/), "3000", "Type amount 3000 (more than the older bill, less than both)");
  await c.click(p.getByRole("button", { name: "UPI", exact: true }), "Choose mode UPI");
  await c.type(p.getByLabel("Reference"), "UPI123456", "Type short reference");
  await c.click(p.getByRole("button", { name: "Record payment" }), "Click Record payment");
  await c.look("After a payment that covers one bill and part of the other");
  console.log((await c.text()).slice(0, 700));
});
