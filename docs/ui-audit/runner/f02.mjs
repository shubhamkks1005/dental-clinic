import { flow } from "./lib2.mjs";
const TOMORROW = new Date(Date.now() + 330 * 60_000 + 86_400_000).toISOString().slice(0, 10); // tomorrow in IST, computed, so the script works on any day
const vp = process.argv[3] || "phone";
await flow({ id: process.argv[2] || "F02-phone-full-day", role: "receptionist", vp }, async (c) => {
  const p = c.page; const d = () => p.locator("dialog[open]");
  await c.go("/app", "Receptionist on a phone: Today"); await c.m("Today (receptionist)");
  await c.go("/app/patients/new", "New patient form"); await c.m("New patient (empty)");
  await c.type(p.getByLabel("Full name"), "Phone Tester", "Name"); await c.pick(p.getByLabel("Gender"), "Female", "Gender"); await c.type(p.getByLabel("Or age (years)"), "33", "Age"); await c.type(p.locator("input[type=tel]").first(), "9000099040", "Mobile");
  await c.click(p.getByRole("button", { name: "Save patient" }), "Save patient"); await c.m("Patient saved screen");
  await c.click(p.getByRole("button", { name: "Book appointment" }).or(p.getByRole("link", { name: "Book appointment" })), "Book appointment");
  await c.pick(d().getByLabel("Visit type"), { label: "Consultation" }, "Consultation");
  await d().getByLabel("Date").fill(TOMORROW); await p.waitForTimeout(1200); await c.look("Book dialog with times (phone)"); await c.m("Book dialog");
  await c.click(d().getByRole("button", { name: /^\d{1,2}:\d{2} [AP]M$/ }).first(), "Pick the first free time");
  await c.type(d().getByLabel(/What they said/), "Phone test", "Note");
  await c.click(d().getByRole("button", { name: "Book", exact: true }), "Book");
  await c.m("Appointments after booking"); await c.go(`/app/appointments?date=${TOMORROW}`, "Calendar tomorrow on the phone"); await c.m("Calendar");
  await c.go("/app/patients", "Patients list"); await c.m("Patients list");
  await c.type(p.getByPlaceholder(/Search by name|mobile|patient code/).last(), "Neha", "Search Neha"); await p.waitForTimeout(900); await c.look("Search result on the phone");
  await c.click(p.getByRole("link", { name: "Neha Testcase" }).first(), "Open Neha");
  await c.m("Profile (receptionist)");
  await c.click(p.getByRole("tab", { name: "Billing", exact: true }), "Billing tab"); await c.m("Billing tab");
  await c.type(p.getByLabel(/Amount/).first(), "500", "Amount 500");
  await c.click(p.getByRole("button", { name: "Record payment" }), "Record payment"); await c.look("After payment on phone");
  await c.go("/app/billing", "Billing (dues)"); await c.m("Dues list");
  await c.go("/app/messages", "Messages"); await c.m("Messages");
  await c.go("/app/more", "More tab"); await c.m("More");
  await c.as("doctor", "Switch to the doctor (same phone)"); await c.m("Today (doctor)");
  await c.click(p.getByRole("button", { name: "Open visit" }).or(p.getByRole("link", { name: "Open visit" })).first(), "Open visit"); await c.m("Visit");
  await c.type(p.getByLabel("Chief complaint"), "Pain on phone test", "Complaint");
  await c.click(p.getByRole("tab", { name: "Chart", exact: true }), "Chart tab"); await c.m("Chart tab");
  await c.click(p.getByRole("tab", { name: "Medicines", exact: true }), "Medicines tab"); await c.m("Medicines tab");
  await c.go("/app/reports", "Reports (doctor)"); await c.m("Reports");
  await c.go("/app/settings", "Settings (doctor)"); await c.m("Settings");
});
