import { flow } from "./lib2.mjs";
await flow({ id: process.argv[2] || "D02-refund-and-cancel-a-bill", role: "receptionist", vp: "laptop" }, async (c) => {
  const p = c.page;
  await c.go("/app/patients", "Receptionist opens Patients");
  await c.click(p.getByRole("link", { name: "Neha Testcase" }).first(), "Open Neha Testcase (one issued bill of ₹2,500, unpaid)");
  await c.click(p.getByRole("tab", { name: "Billing", exact: true }), "Open Billing tab");
  await c.type(p.getByLabel(/Amount/).first(), "500", "Type amount 500");
  await c.click(p.getByRole("button", { name: "Record payment" }), "Record a ₹500 cash payment");
  await c.click(p.getByRole("link", { name: /SB-/ }).first(), "Open the bill (patient says: the bill is wrong, cancel it)");
  await c.look("Receptionist's view of an issued bill: there is no Cancel bill, only a way to ask the doctor");
  // Q1.9 (D4): the receptionist cannot cancel; she asks the doctor with a reason.
  await c.click(p.getByText("More actions"), "Open More actions (Q2.3 moved the cancel actions there)");
  await c.click(p.getByRole("button", { name: "Ask the doctor to cancel" }), "Click Ask the doctor to cancel");
  await c.type(p.getByLabel("Why is it wrong?"), "Wrong procedure billed", "Type the reason");
  await c.click(p.getByRole("button", { name: "Send request" }), "Send the request to the doctor");
  await c.as("doctor", "Switch to the doctor");
  await c.go("/app", "Doctor Today: Waiting for you lists the cancel request");
  await c.look("Doctor Today with the cancel request under Waiting for you");
  c.note("Waiting for you mentions the bill: " + /BILL CANCEL/.test(await c.text()));
  await c.click(p.getByRole("region", { name: "Waiting for you" }).locator("li", { hasText: "BILL CANCEL" }).getByRole("link", { name: "Open", exact: true }), "Open the bill from Waiting for you");
  await c.click(p.getByText("More actions"), "Open More actions");
  await c.click(p.getByRole("button", { name: "Cancel bill" }), "Click Cancel bill");
  await c.look("Cancel panel: money is held, so it says Refund first and Confirm cancel is off");
  c.note("Refund first link shown: " + ((await p.getByRole("link", { name: "Refund first" }).count()) > 0) + " | Confirm cancel enabled: " + (await p.getByRole("button", { name: "Confirm cancel" }).isEnabled()));
  await c.go("/app/patients", "Back to Patients to refund first");
  await c.click(p.getByRole("link", { name: "Neha Testcase" }).first(), "Open Neha Testcase");
  await c.click(p.getByRole("tab", { name: "Billing", exact: true }), "Billing tab");
  await c.pick(p.locator("select:has(option:text-is('Select…'))"), { index: 1 }, "Choose the ₹500 payment to refund");
  await c.type(p.getByLabel(/Amount/).nth(1), "500", "Type refund amount 500");
  await c.type(p.getByLabel("Reason").first(), "Bill was wrong", "Type refund reason");
  await c.click(p.getByRole("button", { name: "Record refund" }), "Click Record refund");
  await c.look("After the refund");
  await c.click(p.getByRole("link", { name: /SB-/ }).first(), "Open the bill again");
  await c.click(p.getByText("More actions"), "Open More actions (Cancel bill sits there since Q2.3)");
  await c.click(p.getByRole("button", { name: "Cancel bill" }), "Click Cancel bill");
  await c.type(p.getByLabel("Reason").last(), "Wrong procedure billed", "Type the reason");
  await c.click(p.getByRole("button", { name: "Confirm cancel" }), "Confirm cancel (nothing paid now)");
  await c.look("Bill cancelled");
  await c.go("/app/patients", "Open Neha again to compare the numbers after the refund");
  await c.click(p.getByRole("link", { name: "Neha Testcase" }).first(), "Open Neha Testcase");
  await c.look("Profile History tab: the refund is listed, what does Outstanding say?");
  const id = p.url().split("/").pop();
  await c.go("/app/print/statement/" + id, "Print the account statement: does it show the refund?");
});
